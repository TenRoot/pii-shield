"""Copy github-repo-template/rules/ into the BUNDLED_RULES block of pii_sanitizer.py.

Run after you change a bundled rule or wordlist:  python tools/bundle_rules.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "pii_sanitizer.py"
RULES = ROOT / "github-repo-template" / "rules"
BEGIN, END = "# BEGIN BUNDLED RULES", "# END BUNDLED RULES"
EXTENSIONS = {".yaml", ".yml", ".json", ".txt", ".lst", ".csv"}


def build_block() -> str:
    lines = [BEGIN + " (generated by tools/bundle_rules.py from github-repo-template/rules/ - do not edit)",
             "BUNDLED_RULES: Dict[str, str] = {"]
    for p in sorted(RULES.rglob("*")):
        if not p.is_file() or p.suffix.lower() not in EXTENSIONS:
            continue
        text = p.read_text("utf-8")
        if '"""' in text or text.endswith("\\"):
            sys.exit(f"{p}: cannot embed as a raw triple-quoted string")
        lines.append(f'    "{p.relative_to(RULES).as_posix()}": r"""{text}""",')
    lines += ["}", END]
    return "\n".join(lines)


def main() -> int:
    src = SCRIPT.read_text("utf-8")
    start, end = src.index(BEGIN), src.index(END) + len(END)
    new = src[:start] + build_block() + src[end:]
    if new == src:
        print("BUNDLED_RULES already up to date")
        return 0
    SCRIPT.write_text(new, "utf-8")
    print(f"updated BUNDLED_RULES in {SCRIPT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
